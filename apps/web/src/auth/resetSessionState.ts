type MutableRef<T> = { current: T };

type WebSessionResetDeps = {
  beginBrowserSignedOutState: () => void | Promise<void>;
  setCommunities: (value: any[]) => void;
  setIsLoadingCommunities: (value: boolean) => void;
  setCommunityRoleById: (value: Record<string, string>) => void;
  setActiveCommunityId: (value: null) => void;
  setCommunityTab: (value: "chat") => void;
  setCommunityMessages: (value: any[]) => void;
  setCommunityMessageInput: (value: string) => void;
  setCommunityChatError: (value: string | null) => void;
  resetCommunityChatDataState: () => void;
  setUnreadCount: (value: number) => void;
  setIsUserAtBottom: (value: boolean) => void;
  isUserAtBottomRef: MutableRef<boolean>;
  setIsSendingCommunityMessage: (value: boolean) => void;
  setReplyingToMessage: (value: null) => void;
  setMessageReactions: (value: any[]) => void;
  setReactionPickerMessageId: (value: string | null) => void;
  setEditingMessageId: (value: string | null) => void;
  setEditingMessageText: (value: string) => void;
  setEditingMessagePrefix: (value: string | null) => void;
  setCommunityResources: (value: any[]) => void;
  setIsLoadingResources: (value: boolean) => void;
  setShowResourceModal: (value: boolean) => void;
  setEditingResourceId: (value: string | null) => void;
  setResourceTitleInput: (value: string) => void;
  setResourceUrlInput: (value: string) => void;
  setResourceBodyInput: (value: string) => void;
  setResourcePinnedInput: (value: boolean) => void;
  setResourceError: (value: string | null) => void;
  setIsSavingResource: (value: boolean) => void;
  setOpenResourceEmbedId: (value: string | null) => void;
  setCommunityEvents?: (value: any[]) => void;
  setIsLoadingCommunityEvents?: (value: boolean) => void;
  setCommunityEventsError?: (value: string | null) => void;
  setCommunityMembers: (value: any[]) => void;
  setCommunitySettingsName: (value: string) => void;
  setCommunitySettingsSlug: (value: string) => void;
  setCommunitySettingsOneLiner: (value: string) => void;
  setCommunitySettingsVisibility: (value: string) => void;
  setCommunitySettingsAvatarUrl: (value: string | null) => void;
  setCommunitySettingsBannerUrl: (value: string | null) => void;
  setCommunitySettingsError: (value: string | null) => void;
  setIsSavingCommunitySettings: (value: boolean) => void;
  setIsSettingsBannerDragOver: (value: boolean) => void;
  setIsSettingsAvatarDragOver: (value: boolean) => void;
  setDiscoverCommunities: (value: any[]) => void;
};

export async function resetWebSessionStateAfterSignOut(deps: WebSessionResetDeps): Promise<void> {
  await deps.beginBrowserSignedOutState();
  deps.setCommunities([]);
  deps.setIsLoadingCommunities(false);
  deps.setCommunityRoleById({});
  deps.setActiveCommunityId(null);
  deps.setCommunityTab("chat");
  deps.setCommunityMessages([]);
  deps.setCommunityMessageInput("");
  deps.setCommunityChatError(null);
  deps.resetCommunityChatDataState();
  deps.setUnreadCount(0);
  deps.setIsUserAtBottom(true);
  deps.isUserAtBottomRef.current = true;
  deps.setIsSendingCommunityMessage(false);
  deps.setReplyingToMessage(null);
  deps.setMessageReactions([]);
  deps.setReactionPickerMessageId(null);
  deps.setEditingMessageId(null);
  deps.setEditingMessageText("");
  deps.setEditingMessagePrefix(null);
  deps.setCommunityResources([]);
  deps.setIsLoadingResources(false);
  deps.setShowResourceModal(false);
  deps.setEditingResourceId(null);
  deps.setResourceTitleInput("");
  deps.setResourceUrlInput("");
  deps.setResourceBodyInput("");
  deps.setResourcePinnedInput(false);
  deps.setResourceError(null);
  deps.setIsSavingResource(false);
  deps.setOpenResourceEmbedId(null);
  deps.setCommunityEvents?.([]);
  deps.setIsLoadingCommunityEvents?.(false);
  deps.setCommunityEventsError?.(null);
  deps.setCommunityMembers([]);
  deps.setCommunitySettingsName("");
  deps.setCommunitySettingsSlug("");
  deps.setCommunitySettingsOneLiner("");
  deps.setCommunitySettingsVisibility("unlisted");
  deps.setCommunitySettingsAvatarUrl(null);
  deps.setCommunitySettingsBannerUrl(null);
  deps.setCommunitySettingsError(null);
  deps.setIsSavingCommunitySettings(false);
  deps.setIsSettingsBannerDragOver(false);
  deps.setIsSettingsAvatarDragOver(false);
  deps.setDiscoverCommunities([]);
}
