// "Test member 1" is TM everywhere, like the member list, not TE. A single
// word (or an id) keeps its first two letters.
export function getInitials(id: string): string {
  const words = String(id ?? "").trim().split(/\s+/).filter((word) => /^[\p{L}]/u.test(word));
  if (words.length >= 2) return `${words[0][0]}${words[1][0]}`.toUpperCase();
  return String(id ?? "").trim().slice(0, 2).toUpperCase();
}

export function downloadTextFile(filename: string, content: string, mime = "text/csv;charset=utf-8"): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function tryCopyTextToClipboard(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Fall back below.
  }
  let textarea: HTMLTextAreaElement | null = null;
  try {
    textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.setAttribute("readonly", "true");
    textarea.style.position = "fixed";
    textarea.style.top = "0";
    textarea.style.left = "-9999px";
    document.body.appendChild(textarea);
    textarea.select();
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    textarea?.remove();
  }
}

export async function copyTextToClipboard(text: string): Promise<void> {
  await tryCopyTextToClipboard(text);
}
